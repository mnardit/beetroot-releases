import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { homedir } from "node:os";
import { resolve, join, dirname, relative, isAbsolute } from "node:path";
import { fileURLToPath } from "node:url";

export const manifestPath = "licenses/third-party.json";
export const noticePath = "THIRD_PARTY_LICENSES.txt";
const byId = (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
export const sha256 = (data) => createHash("sha256").update(data).digest("hex");
const text = (root, path) => readFileSync(resolve(root, path), "utf8").replace(/\r\n/g, "\n");
const json = (root, path) => JSON.parse(text(root, path));

export function inputDigests(root) {
  const lock = json(root, "package-lock.json");
  delete lock.version;
  delete lock.packages[""].version;
  // Same generated Cargo version fields used by prepare-version.mjs; all other
  // lockfile/manifest bytes remain covered, including the root's dependencies.
  const cargoVersion = /(^\[\[package\]\]\nname = "beetroot"\nversion = ")[^"]+(")/m;
  const manifestVersion = /(^\[package\]\n[\s\S]*?^version\s*=\s*")[^"]+("[^\n]*$)/m;
  const cargo = text(root, "src-tauri/Cargo.lock");
  const manifest = text(root, "src-tauri/Cargo.toml");
  if (!cargoVersion.test(cargo) || !manifestVersion.test(manifest)) {
    throw new Error("Cannot identify Beetroot's Cargo version fields");
  }
  return {
    npm: sha256(JSON.stringify(lock)),
    cargo: sha256(cargo.replace(cargoVersion, "$1<project-version>$2")),
    cargoManifest: sha256(manifest.replace(manifestVersion, "$1<project-version>$2")),
  };
}

export function validateManifest(manifest) {
  if (manifest.schemaVersion !== 1 || !manifest.components.length || !manifest.texts.length) {
    throw new Error("Missing third-party license inventory");
  }
  const texts = new Map();
  for (const entry of manifest.texts) {
    if (entry.id !== sha256(entry.text) || texts.has(entry.id) || !entry.text.trim()) {
      throw new Error(`Invalid or duplicate license text: ${entry.id}`);
    }
    if (/Copyright[^\n]*<(?:year|owner|copyright holders)>/i.test(entry.text)) {
      throw new Error(`Unresolved copyright template: ${entry.id}`);
    }
    if (!entry.sources.length || entry.sources.some((url) => new URL(url).protocol !== "https:")) {
      throw new Error(`Missing HTTPS provenance: ${entry.id}`);
    }
    texts.set(entry.id, entry);
  }
  const ids = new Set();
  const referenced = new Set();
  for (const component of manifest.components) {
    if (ids.has(component.id) || !component.license || !component.notices.length) {
      throw new Error(`Missing or duplicate component attribution: ${component.id}`);
    }
    if (component.id !== `${component.ecosystem}:${component.name}@${component.version}`) {
      throw new Error(`Component identity mismatch: ${component.id}`);
    }
    if (new URL(component.source).protocol !== "https:") {
      throw new Error(`Missing component source: ${component.id}`);
    }
    ids.add(component.id);
    for (const id of component.notices) {
      if (!texts.has(id)) throw new Error(`Missing license text for ${component.id}: ${id}`);
      referenced.add(id);
    }
  }
  if (referenced.size !== texts.size) throw new Error("Unreferenced license text in inventory");
}

export function requireComponents(manifest, ids) {
  const known = new Set(manifest.components.map((entry) => entry.id));
  for (const id of ids) {
    if (!known.has(id)) throw new Error(`Missing third-party attribution: ${id}`);
  }
}

export function renderNotices(manifest) {
  const components = [...manifest.components].sort(byId);
  const lines = [
    "Third-party licenses for Beetroot",
    "================================",
    "",
    "Generated from licenses/third-party.json. Do not edit this file directly.",
    "Trailing horizontal whitespace is omitted; original texts remain in the source inventory.",
    "Upstream licenses apply to their respective components, not to Beetroot as a whole.",
    "The inventory conservatively includes build-time and target-specific components.",
    "Existing font, model and model-runtime notices are also supplied separately.",
    "License alternatives and file-level exceptions remain as stated by upstream.",
    "Version-specific source links below provide the unchanged component sources.",
    "",
    "Component inventory",
    "===================",
  ];
  for (const component of components) {
    lines.push(
      "",
      component.id,
      `Declared license: ${component.license}`,
      `Source: ${component.source}`,
    );
    if (component.displayName) lines.push(component.displayName);
    if (component.note) lines.push(component.note);
    lines.push(`Notice IDs: ${component.notices.join(", ")}`);
  }
  for (const entry of [...manifest.texts].sort(byId)) {
    lines.push(
      "",
      "============================================================",
      `Notice ${entry.id}`,
      `Used by: ${components
        .filter((c) => c.notices.includes(entry.id))
        .map((c) => c.id)
        .join(", ")}`,
      ...entry.sources.map((url) => `Source: ${url}`),
      "",
      entry.text,
    );
  }
  return `${lines.join("\n").replace(/[\t ]+$/gm, "")}\n`;
}

function validateNpm(root, manifest) {
  const lock = json(root, "package-lock.json");
  const ids = Object.entries(lock.packages)
    .filter(([path, pkg]) => path && !pkg.dev)
    .map(([path, pkg]) => {
      const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
      return `npm:${name}@${pkg.version}`;
    });
  requireComponents(manifest, ids);
}

export function cargoComponentIds(metadata) {
  const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
  const seen = new Set();
  function visit(id) {
    if (seen.has(id)) return;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((kind) => kind.kind === null || kind.kind === "build")) visit(dep.pkg);
    }
  }
  visit(metadata.resolve.root);
  return metadata.packages
    .filter((pkg) => pkg.source && seen.has(pkg.id))
    .map((pkg) => `cargo:${pkg.name}@${pkg.version}`);
}

function cargoMetadata(root) {
  return JSON.parse(
    execFileSync(
      "cargo",
      [
        "metadata",
        "--format-version",
        "1",
        "--locked",
        "--filter-platform",
        "x86_64-pc-windows-msvc",
        "--manifest-path",
        "src-tauri/Cargo.toml",
      ],
      { cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
    ),
  );
}

export function checkLicenses(root, { write = false, refreshInputs = false } = {}) {
  const manifest = json(root, manifestPath);
  validateManifest(manifest);
  validateNpm(root, manifest);
  const actual = inputDigests(root);
  if (refreshInputs) {
    requireComponents(manifest, cargoComponentIds(cargoMetadata(root)));
    manifest.inputs = actual;
  } else if (Object.keys(actual).some((key) => actual[key] !== manifest.inputs[key])) {
    throw new Error(
      "Dependency inputs changed. Review licenses/README.md before refreshing attribution.",
    );
  }
  const assetPaths = ["src/fonts", "public/model"].flatMap((dir) =>
    readdirSync(resolve(root, dir), { withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) => `${dir}/${entry.name}`),
  );
  if (
    assetPaths.length !== manifest.assets.length ||
    assetPaths.some((path) => !manifest.assets.some((asset) => asset.path === path))
  ) {
    throw new Error("Licensed asset inventory changed");
  }
  for (const asset of manifest.assets) {
    const data =
      asset.encoding === "utf8" ? text(root, asset.path) : readFileSync(resolve(root, asset.path));
    if (sha256(data) !== asset.sha256) {
      throw new Error(`Licensed asset changed: ${asset.path}`);
    }
  }
  const rendered = renderNotices(manifest);
  if (write) {
    writeFileSync(resolve(root, noticePath), rendered);
    if (refreshInputs)
      writeFileSync(resolve(root, manifestPath), `${JSON.stringify(manifest, null, 2)}\n`);
  } else if (text(root, noticePath) !== rendered) {
    throw new Error("THIRD_PARTY_LICENSES.txt is stale; run npm run licenses:write");
  }
  return manifest;
}

export function licenseCheckPlugin() {
  let root;
  return {
    name: "beetroot-third-party-licenses",
    apply: "build",
    configResolved(config) {
      root = config.root;
    },
    generateBundle(_options, bundle) {
      const manifest = checkLicenses(root);
      const ids = new Set();
      const packages = new Map();
      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== "chunk") continue;
        for (const [moduleId, info] of Object.entries(chunk.modules)) {
          if (!info.renderedLength) continue;
          const match = moduleId
            .replaceAll("\\", "/")
            .match(/(?:^|\/)(.*node_modules\/(?:@[^/]+\/)?[^/]+)/);
          if (!match) continue;
          const path = resolve(root, match[1].replace(/^\0/, ""));
          if (!packages.has(path)) packages.set(path, json(path, "package.json"));
          const pkg = packages.get(path);
          ids.add(`npm:${pkg.name}@${pkg.version}`);
        }
      }
      requireComponents(manifest, ids);
    },
  };
}

export function checkNativeLicenses(root, manifest) {
  const version = execFileSync("rustc", ["--version"], { encoding: "utf8" }).split(" ")[1];
  if (version !== manifest.native.rust) throw new Error(`Unreviewed Rust toolchain: ${version}`);
  const metadata = cargoMetadata(root);
  requireComponents(manifest, cargoComponentIds(metadata));
  const cargoHome = process.env.CARGO_HOME ?? join(homedir(), ".cargo");
  const registry = join(cargoHome, "registry", "src");
  for (const item of manifest.native.files) {
    let path;
    if (item.kind === "tauri-cache") {
      if (!process.env.LOCALAPPDATA)
        throw new Error("Native license verification requires Windows");
      path = join(process.env.LOCALAPPDATA, "tauri", item.path);
    } else if (item.kind === "crate") {
      const pkg = metadata.packages.find((p) => `${p.name}@${p.version}` === item.package);
      if (!pkg) throw new Error(`Missing native crate: ${item.package}`);
      path = resolve(dirname(pkg.manifest_path), item.path);
      const local = relative(registry, path);
      if (isAbsolute(local) || local.startsWith(".."))
        throw new Error("Native crate is not from the registry");
    } else {
      throw new Error(`Unknown native artifact kind: ${item.kind}`);
    }
    if (sha256(readFileSync(path)) !== item.sha256)
      throw new Error(`Native artifact changed: ${item.path}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = new Set(process.argv.slice(2));
  for (const arg of args) {
    if (!["--write", "--refresh-inputs", "--native"].includes(arg))
      throw new Error(`Unknown option: ${arg}`);
  }
  if (args.has("--refresh-inputs") && !args.has("--write"))
    throw new Error("--refresh-inputs requires --write");
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const manifest = checkLicenses(root, {
    write: args.has("--write"),
    refreshInputs: args.has("--refresh-inputs"),
  });
  if (args.has("--native")) checkNativeLicenses(root, manifest);
  console.log(
    `Third-party attribution verified: ${manifest.components.length} components, ${manifest.texts.length} texts`,
  );
}
